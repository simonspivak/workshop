export function mockMedia(kind: MockMediaKind): { bytes: Uint8Array; contentType: string; ext: string } {
  switch (kind) {
    case "image":
      return { bytes: decode(IMAGE_JPEG), contentType: "image/jpeg", ext: "jpg" };
    case "video":
      return { bytes: decode(VIDEO_MP4), contentType: "video/mp4", ext: "mp4" };
    case "audio":
      return { bytes: decode(AUDIO_WAV), contentType: "audio/wav", ext: "wav" };
  }
}
